#!/usr/bin/env node
/**
 * Verifies that the published packages a product installs came from where the
 * build claims.
 *
 * ## What the build record is, and is not
 *
 * `build-info.json` records an identity: app commit, core commit, ui commit,
 * lockfile hash. Every one of those values is written by the build itself, so
 * the document agrees with itself by construction. Recording an identity is not
 * verifying it.
 *
 * This verifier asks the registry instead: for each `@zeus-js/*` and
 * `@zeus-web/*` package the lockfile pins, fetch its SLSA attestation, check
 * the Sigstore signature, and bind the statement's subject to the bytes the
 * lockfile says will be installed. A document that names a commit the
 * attestation does not is `INVALID`, not `VERIFIED`.
 *
 * ## Why the packages do not share one source
 *
 * `@zeus-js/*` core packages come from `baicie/zeus`; `@zeus-web/*` come from
 * `baicie/zeus-ui`; `@zeus-js/vite-plugin` and `@zeus-js/devtools-consumer` are
 * on their own version lines and their own tags. Assuming one Core tag covers
 * every package is how a report names a commit that never built the package it
 * describes.
 *
 * Usage:
 *   node scripts/release/verify-provenance.mjs --product admin [--offline]
 *     [--build-info <file>] [--out <file>]
 */
import fs from 'node:fs'
import path from 'node:path'
import process from 'node:process'
import { parseArgs } from 'node:util'

import { readProducts } from './deployment-plan.mjs'
/*
 * The attestation module is TypeScript, and this file is imported by a plain
 * `node --test` suite that cannot transform it. The import is dynamic so the
 * pure helpers below — the lockfile reader, the verdict rules — can be tested
 * without a TypeScript loader; only a real verification needs the module, and
 * that path runs under `tsx`.
 */
async function loadAttestation() {
  return import('./provenance/attestation.ts')
}

const root = path.resolve(import.meta.dirname, '../..')

/**
 * Where each package family comes from, in `owner/repo` form.
 *
 * `verifyAttestation` compares this against the repository it parses out of the
 * attestation, which is `owner/repo` — passing a full URL fails the comparison
 * and reports every package as `attestation does not describe this package`,
 * which reads like a provenance failure and is a formatting one.
 */
export const SOURCE_REPOSITORIES = {
  '@zeus-js/': 'baicie/zeus',
  '@zeus-web/': 'baicie/zeus-ui',
}

/** Packages on their own version line, published from their own tags. */
export const INDEPENDENT_PACKAGES = new Set([
  '@zeus-js/vite-plugin',
  '@zeus-js/devtools-consumer',
])

export const VERDICTS = ['VERIFIED', 'INVALID', 'MISSING', 'NETWORK_ERROR', 'NOT_RUN']

/**
 * Which workflow signs each package, as data.
 *
 * The map lives here rather than in the TypeScript attestation module so that a
 * plain `node --test` suite can assert it. `attestation.ts` imports it — the
 * dependency runs one way, and the verification code keeps its types.
 *
 * A repository can publish from more than one workflow: `baicie/zeus` ships its
 * fixed group from `release.yml` and its independent lines from
 * `devtools-release.yml`. Keying by repository alone rejected every
 * independently published package with `expected …/release.yml, got
 * …/devtools-release.yml` — a real signature from a real publish.
 */
export const SIGNER_WORKFLOWS = {
  '@zeus-js/vite-plugin': 'devtools-release.yml',
  '@zeus-js/devtools-consumer': 'devtools-release.yml',
  'create-zeus': 'devtools-release.yml',
  '@zeus-js/zeus': 'release.yml',
  '@zeus-web/button': 'publish.yml',
}

/** The fallback when a package is not named above. */
const DEFAULT_SIGNER_WORKFLOW = 'publish.yml'

/**
 * The workflow a package is expected to have been signed by.
 *
 * Exported as a function so callers do not reimplement the lookup, and so the
 * default is stated once.
 */
export function signerWorkflowFor(packageName) {
  return SIGNER_WORKFLOWS[packageName] ?? DEFAULT_SIGNER_WORKFLOW
}

/** The full certificate identity npm's publisher holds for a package at a ref. */
export function expectedSignerIdentityFor(repository, ref, packageName) {
  return `https://github.com/${repository}/.github/workflows/${signerWorkflowFor(packageName)}@${ref}`
}

/**
 * Parses `pnpm-lock.yaml` for the Zeus packages and their integrity.
 *
 * A full YAML parser would be the wrong dependency here: the lockfile is
 * generated by pnpm and the shape being read is two lines per entry. Reading it
 * as text keeps this verifier installable without adding a parser that then has
 * to track pnpm's schema.
 */
export function readLockedPackages(lockfileText) {
  const packages = []
  const seen = new Set()

  /*
   * Entries look like:
   *
   *   '@zeus-js/zeus@0.2.0-rc.5':
   *     resolution: {integrity: sha512-…}
   */
  const entry = /^ {2}'(@zeus-(?:js|web)\/[^']+)':\s*$/gm
  let match

  while ((match = entry.exec(lockfileText)) !== null) {
    /*
     * Strip the peer suffix before looking for the version separator.
     *
     * `@zeus-js/output-react-wrapper@0.2.0-rc.5(@zeus-js/web-c-runtime@0.2.0-rc.5)(rolldown@…)`
     * contains several `@` signs; `lastIndexOf('@')` found one inside a peer and
     * produced a "package name" that was half of the real one, so every wrapped
     * package looked like it had no integrity in the lockfile.
     */
    const spec = match[1].split('(')[0]
    const at = spec.lastIndexOf('@')

    if (at <= 0) continue

    const name = spec.slice(0, at)

    /*
     * pnpm writes a peer-suffixed key for every package whose resolved peers
     * differ: `@zeus-js/vite-plugin@0.0.5(vite@8.3.8)(esbuild@…)`. The version
     * is the part before the first `(`, and the plain key `…@0.0.5` is a
     * separate entry that carries the integrity.
     *
     * Treating the whole suffix as the version sent the registry query to a
     * version that does not exist, and the report called 31 packages
     * "the lockfile pins no integrity" when the lockfile had it all along.
     */
    const version = spec.slice(at + 1)

    const key = `${name}@${version}`

    const rest = lockfileText.slice(match.index, match.index + 400)
    const integrity = /integrity:\s*(sha\d+-[A-Za-z0-9+/=]+)/.exec(rest)?.[1] ?? null

    /*
     * A duplicate is not always redundant. pnpm writes both
     * `…@0.0.5(vite@…)` and `…@0.0.5`, and only the second carries the
     * integrity — so the first one wins the `seen` check and the real entry is
     * skipped. Keep whichever has an integrity, preferring the first when both
     * do.
     */
    const existing = packages.findIndex(entry => `${entry.name}@${entry.version}` === key)

    if (existing === -1) {
      packages.push({ name, version, integrity })
    } else if (packages[existing].integrity === null && integrity !== null) {
      packages[existing] = { name, version, integrity }
    }

    seen.add(key)
  }

  return packages
}

/** The repository a package is expected to have been built from. */
export function expectedRepository(name) {
  for (const [prefix, repository] of Object.entries(SOURCE_REPOSITORIES)) {
    if (name.startsWith(prefix)) return repository
  }

  return null
}

/**
 * Compares what the attestation says against what the build claims.
 *
 * Every field is reported, not just the verdict: a reader has to be able to see
 * *which* value disagreed — a wrong commit and a wrong repository are different
 * incidents.
 */
export function judgePackage(locked, attestation, claims) {
  const base = {
    name: locked.name,
    version: locked.version,
    lockfileIntegrity: locked.integrity ?? null,
  }

  if (!attestation) {
    return { ...base, verdict: 'MISSING', reason: 'the registry returned no attestation for this version' }
  }

  const expected = expectedRepository(locked.name)

  if (attestation.repository && expected && attestation.repository !== expected) {
    return {
      ...base,
      attestedSubjectDigest: attestation.subjectDigest ?? null,
      expectedRepository: expected,
      actualRepository: attestation.repository,
      verdict: 'INVALID',
      reason: `attestation names ${attestation.repository}, expected ${expected}`,
    }
  }

  /*
   * The core commit a build claims is only meaningful for packages published
   * from the core line. An independent package has its own tags, so comparing
   * its commit against the core's would report a mismatch that is not one.
   */
  const claimsCommit = !INDEPENDENT_PACKAGES.has(locked.name) && expected?.includes('zeus-ui') === false
    ? claims?.coreCommit
    : undefined

  if (claimsCommit && attestation.commit && claimsCommit !== attestation.commit) {
    return {
      ...base,
      attestedSubjectDigest: attestation.subjectDigest ?? null,
      expectedCommit: claimsCommit,
      actualCommit: attestation.commit,
      verdict: 'INVALID',
      reason: `attestation names commit ${attestation.commit?.slice(0, 8)}, build-info claims ${claimsCommit.slice(0, 8)}`,
    }
  }

  if (attestation.subjectDigest && locked.integrity === null) {
    return {
      ...base,
      attestedSubjectDigest: attestation.subjectDigest,
      verdict: 'INVALID',
      reason: 'the lockfile pins no integrity for this package, so the subject cannot be bound to bytes',
    }
  }

  return {
    ...base,
    attestedSubjectDigest: attestation.subjectDigest ?? null,
    expectedRepository: expected ?? undefined,
    actualRepository: attestation.repository ?? undefined,
    expectedCommit: claimsCommit,
    actualCommit: attestation.commit ?? undefined,
    signerIdentity: attestation.signerIdentity ?? undefined,
    verdict: 'VERIFIED',
  }
}

/** Rolls per-package verdicts into one product verdict. */
export function summarise(productId, packages, claims) {
  const verified = packages.filter(entry => entry.verdict === 'VERIFIED').length
  const invalid = packages.filter(entry => entry.verdict === 'INVALID' || entry.verdict === 'MISSING')
  const network = packages.filter(entry => entry.verdict === 'NETWORK_ERROR')
  const notRun = packages.filter(entry => entry.verdict === 'NOT_RUN')

  /*
   * A network failure is not a pass and not a lie: the answer is unknown.
   * Reporting INCOMPLETE says exactly that, where PASS would claim a check that
   * did not happen and FAIL would blame the artifact for a flaky connection.
   */
  /*
   * An empty list is INCOMPLETE, not PASS.
   *
   * `[].every(...)` is true — the same shape that let a browser gate report
   * green after running zero engines. A report that verified nothing must not
   * read as a clean bill of health.
   */
  let verdict = 'PASS'

  if (packages.length === 0) verdict = 'INCOMPLETE'
  else if (invalid.length > 0) verdict = 'FAIL'
  else if (network.length > 0 || notRun.length > 0) verdict = 'INCOMPLETE'

  return {
    schema: 'zeus.ecosystem.provenance-report/v1',
    productId,
    sourceCommit: claims?.appCommit ?? null,
    lockfileSha256: claims?.lockfileSha256 ?? null,
    buildInfoSha256: claims?.buildInfoSha256 ?? null,
    packages,
    counts: { total: packages.length, verified, invalid: invalid.length, network: network.length, notRun: notRun.length },
    verdict,
  }
}

/**
 * Asks the registry about one package.
 *
 * Three outcomes that must not be conflated:
 *
 *   - the registry answered and the attestation verifies   -> VERIFIED
 *   - the registry answered and something disagrees        -> INVALID
 *   - the registry did not answer                          -> NETWORK_ERROR
 *
 * A timeout reported as INVALID would blame the package for the connection; a
 * timeout reported as VERIFIED would claim a check nobody performed.
 */
export async function verifyOnePackage(locked, claims, options = {}) {
  const registry = options.registry ?? 'https://registry.npmjs.org'
  const fetchImpl = options.fetch ?? globalThis.fetch
  const repository = expectedRepository(locked.name)

  if (!locked.integrity) {
    return {
      name: locked.name,
      version: locked.version,
      lockfileIntegrity: null,
      verdict: 'INVALID',
      reason: 'the lockfile pins no integrity for this package, so nothing can be bound to bytes',
    }
  }

  /*
   * The attestation helpers are injectable so a test can supply them without a
   * TypeScript loader: `node --test` cannot import the `.ts` module, and the
   * alternative is a test that only runs under a different runner than the rest
   * of the suite.
   */
  const attestation = options.attestation ?? (await loadAttestation())
  const { attestationUrl, findSlsaBundle } = attestation
  const verifyImpl = options.verify ?? attestation.verifyAttestation

  let response

  try {
    response = await fetchImpl(attestationUrl(locked.name, locked.version, registry), {
      headers: { accept: 'application/json' },
      signal: AbortSignal.timeout(options.timeoutMs ?? 20_000),
    })
  } catch (error) {
    return {
      name: locked.name,
      version: locked.version,
      lockfileIntegrity: locked.integrity,
      verdict: 'NETWORK_ERROR',
      reason: `the registry did not answer: ${error instanceof Error ? error.message : String(error)}`,
    }
  }

  if (response.status === 404) {
    return {
      name: locked.name,
      version: locked.version,
      lockfileIntegrity: locked.integrity,
      verdict: 'MISSING',
      reason: 'the registry publishes no attestation for this version',
    }
  }

  if (!response.ok) {
    return {
      name: locked.name,
      version: locked.version,
      lockfileIntegrity: locked.integrity,
      verdict: 'NETWORK_ERROR',
      reason: `the registry answered HTTP ${response.status}`,
    }
  }

  const body = await response.json().catch(() => null)
  const bundle = body ? findSlsaBundle(body) : undefined

  if (!bundle) {
    return {
      name: locked.name,
      version: locked.version,
      lockfileIntegrity: locked.integrity,
      verdict: 'MISSING',
      reason: 'the registry answered but carried no SLSA provenance statement',
    }
  }

  /* The subject has to be these exact bytes, which is what the lockfile pins. */
  const expectedSha512 = decodeIntegritySha512(locked.integrity)

  const result = await verifyImpl(bundle, {
    name: locked.name,
    version: locked.version,
    ...(repository ? { repository } : {}),
    ...(expectedSha512 ? { expectedSha512 } : {}),
  })

  if (!result.ok) {
    return {
      name: locked.name,
      version: locked.version,
      lockfileIntegrity: locked.integrity,
      verdict: 'INVALID',
      reason: result.failure?.detail ?? 'the attestation did not verify',
    }
  }

  /*
   * The verified facts live under `attestation`, not at the top level — reading
   * the wrong path returned `undefined` for repository and commit on a package
   * that had just been verified, which is a report that says VERIFIED and
   * carries no evidence for it.
   */
  const verified = result.attestation

  return {
    name: locked.name,
    version: locked.version,
    lockfileIntegrity: locked.integrity,
    expectedRepository: repository ?? undefined,
    actualRepository: verified.repository,
    actualCommit: verified.commit,
    signerIdentity: verified.signerIdentity,
    signerIssuer: verified.signerIssuer,
    tlogEntries: verified.tlogEntries,
    verdict: 'VERIFIED',
  }
}

/** `sha512-<base64>` from the lockfile, as the verifier wants it. */
export function decodeIntegritySha512(integrity) {
  const match = /^sha512-([A-Za-z0-9+/=]+)$/.exec(integrity.trim())

  return match ? match[1] : undefined
}

if (process.argv[1] && import.meta.url === `file://${process.argv[1]}`) {
  const { values } = parseArgs({
    options: {
      product: { type: 'string' },
      'build-info': { type: 'string' },
      out: { type: 'string' },
      offline: { type: 'boolean', default: false },
    },
  })

  const productId = values.product

  if (!productId) {
    console.error('usage: verify-provenance.mjs --product <id> [--offline] [--build-info <file>] [--out <file>]')
    process.exit(1)
  }

  const declaration = readProducts(root)

  if (!declaration.products.some(entry => entry.productId === productId)) {
    console.error(`"${productId}" is not a declared product`)
    process.exit(1)
  }

  const lockfilePath = path.join(root, 'pnpm-lock.yaml')

  if (!fs.existsSync(lockfilePath)) {
    console.error(`${lockfilePath} is missing`)
    process.exit(1)
  }

  const locked = readLockedPackages(fs.readFileSync(lockfilePath, 'utf8'))

  if (locked.length === 0) {
    console.error('the lockfile pins no Zeus packages; this verifier would report on nothing')
    process.exit(1)
  }

  const buildInfoPath = values['build-info'] ?? path.join(root, 'apps', productId, 'dist/build-info.json')
  const buildInfo = fs.existsSync(buildInfoPath)
    ? JSON.parse(fs.readFileSync(buildInfoPath, 'utf8'))
    : null

  const claims = buildInfo
    ? {
        appCommit: buildInfo.app?.commit,
        coreCommit: buildInfo.core?.commit,
        uiCommit: buildInfo.ui?.commit,
        lockfileSha256: buildInfo.lockfileSha256,
        buildInfoSha256: null,
      }
    : null

  /*
   * `--offline` is the ordinary pull-request mode: it answers whether the
   * lockfile is even in a shape that could be verified, and reports every
   * package as NOT_RUN. It never reports PASS.
   */
  let packages

  if (values.offline) {
    packages = locked.map(entry => ({
      name: entry.name,
      version: entry.version,
      lockfileIntegrity: entry.integrity,
      verdict: 'NOT_RUN',
      reason: 'offline: no registry query was made',
    }))
  } else {
    packages = []

    for (const entry of locked) {
      packages.push(await verifyOnePackage(entry, claims))
    }
  }

  const report = summarise(productId, packages, claims)

  const text = `${JSON.stringify(report, null, 2)}\n`

  if (values.out) fs.writeFileSync(path.resolve(values.out), text)

  console.log(text)
  console.log(`verdict: ${report.verdict} (${report.counts.verified}/${report.counts.total} verified)`)

  /* INCOMPLETE is not success: an unverified candidate must not read as green. */
  process.exit(report.verdict === 'PASS' ? 0 : 1)
}
